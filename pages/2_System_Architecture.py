st.header("8 · What requires AI and what does not?")
st.table([
{"Feature":"Question generation","Execution":"LLM/API or local Ollama model when configured"},
{"Feature":"Speech transcription","Execution":"Speech API (Gemini/Groq); local speech model needs separate installation"},
{"Feature":"Gibberish pre-check","Execution":"Python rules; optional LLM semantic check"},
{"Feature":"Answer evaluation","Execution":"LLM/API or local Ollama model; Python validates and aggregates output"},
{"Feature":"Login and PIN verification","Execution":"Python cryptographic hashing; no LLM required"},
{"Feature":"History and progress","Execution":"Browser storage + Python calculations; no LLM required"},
{"Feature":"Charts and report export","Execution":"Python/Streamlit; no LLM required"},
])

