flow = [
("01 · Candidate access", "Candidate enters a name and creates a Candidate ID + 6-digit PIN, or signs in. The PIN is salted and hashed by the backend; the profile record is kept in this browser's localStorage."),
("02 · Interview setup", "Streamlit collects target role, experience level, interview type, interviewer persona, question count and optional project context. Python validates and stores these values in Streamlit session state."),
("03 · Question selection", "The current interview plan is assembled by Python from the role/category question bank. Dynamic technical challenge generation can call a configured LLM provider."),
("04 · Answer capture", "Typed answers arrive as UTF-8 text. Audio arrives as bytes plus a MIME type such as audio/webm or audio/wav; the speech module sends supported audio to a configured transcription provider."),
("05 · Input validation", "Python checks empty input and obvious random-character patterns. Question-specific semantic relevance and sufficiency are not fully guaranteed by the simple regex gate; those require model evaluation."),
("06 · LLM evaluation", "Python builds a prompt containing the question, answer, optional follow-up, candidate context and rubric. It sends an HTTPS JSON request to the selected provider and receives a JSON response containing scores and feedback."),
("07 · Result validation", "Python parses the response, bounds criterion scores to the allowed range and calculates the weighted overall score. Invalid responses or provider failures must be surfaced rather than silently represented as successful AI output."),
("08 · History and analytics", "The session is serialized as JSON and written by a browser component to localStorage under the current candidate key. History and progress screens read those saved session objects; charts are calculated by Python."),
("09 · Report export", "Python converts the stored session/result objects into Markdown, HTML and JSON export formats. The report is not generated by asking the LLM to invent a result."),
]
for title, body in flow:
    st.markdown(f'<div class="step"><div class="kicker">{title}</div>{body}</div>', unsafe_allow_html=True)

st.header("2 · What format travels between components?")
st.table([
{"Stage":"Browser → Streamlit","Data format":"Text values, widget state, uploaded file bytes","Why":"Candidate input and configuration"},
{"Stage":"Streamlit → Python backend","Data format":"Python strings, dictionaries, dataclasses, bytes","Why":"Validation and application logic"},
{"Stage":"Python → hosted LLM API","Data format":"HTTPS POST; JSON body; UTF-8 prompt text; JSON response","Why":"Question generation/evaluation"},
{"Stage":"Python → speech API","Data format":"Multipart/form-data audio file (Groq) or JSON with base64 audio (Gemini)","Why":"Speech-to-text transcription"},
{"Stage":"Python → Ollama (when configured)","Data format":"Local HTTP JSON request/response","Why":"Local model inference; not the same as a hosted API"},
{"Stage":"Python → browser storage","Data format":"JSON string serialized with json.dumps","Why":"Save candidate profiles and interview sessions"},
{"Stage":"Python → report download","Data format":"Markdown, HTML or JSON","Why":"Human-readable and machine-readable output"},
])

